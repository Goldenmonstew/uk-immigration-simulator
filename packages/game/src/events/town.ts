export const townEvents: GameEvent[] = scenes.map(
  ([npc, id, title, titleEn, zhCN, en, first, firstEn, second, secondEn]) => ({
    id: `town-${npc}-${id}`,
    title: t(title, titleEn),
    text: t(zhCN, en),
    weight: 2,
    once: true,
    channel: `npc:${npc}`,
    speaker: npc,
    choices: [
      {
        id: 'stay',
        label: t(first, firstEn),
        effects: [{ type: 'stat', key: 'mood', delta: b.heartMood }],
        sets: [`town-${npc}-${id}-shared`],
      },
      {
        id: 'help',
        label: t(second, secondEn),
        effects: [{ type: 'stat', key: 'health', delta: b.heartHelp }],
        sets: [`town-${npc}-${id}-shared`],
      },
    ],
  }),
);
for (let i = 0; i < 10; i += 2)
  townEvents[i + 1].requires = [`${townEvents[i].id}-shared`];
for (const event of townEvents.slice(0, 11))
  event.when = [{ npc: event.speaker!, heartsMin: 2 }];
townEvents[11].requires = ['lina-can-stay'];
townEvents[12].requires = ['lina-will-leave'];
for (const event of [townEvents[11], townEvents[12]]) event.channel = 'phone';
townEvents[13].requires = ['lina-left'];
