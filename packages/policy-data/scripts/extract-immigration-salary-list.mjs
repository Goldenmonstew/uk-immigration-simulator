import { readFileSync, writeFileSync } from 'node:fs';
import { URL } from 'node:url';

const snapshot =
  '2025-11-11-immigration-rules-appendix-immigration-salary-list.html';
const html = readFileSync(
  new URL(`../../../policy-sources/${snapshot}`, import.meta.url),
  'utf8',
);
const table = html.match(/<table>[\s\S]*?<\/table>/)[0];
const body = table.match(/<tbody>([\s\S]*?)<\/tbody>/)[1];

function text(value) {
  return value
    .replace(/<[^>]*>/g, ' ')
    .replaceAll('&amp;', '&')
    .replace(/\s+/g, ' ')
    .trim();
}

const [countryHeaders, ...rows] = [
  ...body.matchAll(/<tr\b[^>]*>([\s\S]*?)<\/tr>/g),
].map((row) =>
  [...row[1].matchAll(/<td\b[^>]*>([\s\S]*?)<\/td>/g)].map((cell) =>
    text(cell[1]),
  ),
);
const entries = rows.map((cells) => {
  const occupation = cells[0].match(/^(\d{4}) (.+)$/);
  if (!occupation) throw new Error(`Invalid ISL occupation: ${cells[0]}`);
  const separator = occupation[2].indexOf(' – ');
  const title =
    separator < 0 ? occupation[2] : occupation[2].slice(0, separator);
  const criteria =
    separator < 0 ? undefined : occupation[2].slice(separator + 3);
  // The source has four Yes / - columns under a shared inclusion header.
  const nations = countryHeaders
    .slice(1, -1)
    .filter((_, index) => cells[index + 1] === 'Yes')
    .join(', ')
    .replace(/, ([^,]+)$/, ' and $1');
  const removalDate = cells.at(-1);
  return {
    socCode: occupation[1],
    title,
    ...(criteria ? { criteria } : {}),
    nations,
    ...(removalDate ? { removalDate } : {}),
  };
});

function quote(value) {
  return `'${value.replaceAll('\\', '\\\\').replaceAll("'", "\\'")}'`;
}

const renderedEntries = entries
  .map((entry) =>
    [
      '    {',
      ...Object.entries(entry).map(([key, value]) => {
        const literal = quote(value);
        const line = `      ${key}: ${literal},`;
        return line.length > 80 ? `      ${key}:\n        ${literal},` : line;
      }),
      '    },',
    ].join('\n'),
  )
  .join('\n');
const output = `import type { SourceRef } from '../types';

// Generated by scripts/extract-immigration-salary-list.mjs; do not edit manually.
// SRC-019: policy-sources/${snapshot}.
// Preserve every occupation row in source order, including repeated SOC codes.
// Criteria retain the source wording; HTML breaks and whitespace are normalised.
// Nations join the original country headers whose source cells contain Yes.

export interface ImmigrationSalaryListEntry {
  /** Four-digit SOC 2020 occupation code. */
  socCode: string;
  /** Occupation name before the first criteria separator. */
  title: string;
  /** Further criteria from the same cell, without interpretation. */
  criteria?: string;
  /** Included nations, in the original country-header order. */
  nations: string;
  /** Removal date in the source wording, when present. */
  removalDate?: string;
}

export const immigrationSalaryListOccupations: {
  source: SourceRef;
  entries: ImmigrationSalaryListEntry[];
} = {
  source: {
    srcId: 'SRC-019',
    locator:
      'Unnumbered introductory paragraph; occupation table; SOC 2020 rows',
  },
  entries: [
${renderedEntries}
  ],
};
`;

writeFileSync(
  new URL('../src/data/immigration-salary-list.ts', import.meta.url),
  output,
);
