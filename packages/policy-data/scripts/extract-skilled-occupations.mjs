import { readFileSync, writeFileSync } from 'node:fs';
import { URL } from 'node:url';

const snapshot =
  '2025-11-11-immigration-rules-appendix-skilled-occupations.html';
const html = readFileSync(
  new URL(`../../../policy-sources/${snapshot}`, import.meta.url),
  'utf8',
);
const rateTables = ['1', '1a', '2', '2aa', '2a', '2b'];
const tables = new Map(
  [
    ...html.matchAll(
      /<h2\b[^>]*id="table-([a-z\d]+)-[^>]*>[\s\S]*?(<table>[\s\S]*?<\/table>)/g,
    ),
  ].map((match) => [match[1], match[2]]),
);

function text(value) {
  return value
    .replace(/<[^>]*>/g, ' ')
    .replaceAll('&amp;', '&')
    .replace(/\s+/g, ' ')
    .trim();
}

function parseTable(table) {
  const source = tables.get(table);
  const headers = [...source.matchAll(/<th\b[^>]*>([\s\S]*?)<\/th>/g)].map(
    (match) => text(match[1]),
  );
  const socColumn = headers.indexOf('SOC 2020 occupation code');
  const rateColumn = headers.findIndex((header) =>
    header.startsWith('Going rate ('),
  );
  if (socColumn < 0 || rateColumn < 0) {
    throw new Error(`Missing SOC 2020 or going rate column in Table ${table}`);
  }
  const rows = [...source.matchAll(/<tr\b[^>]*>([\s\S]*?)<\/tr>/g)]
    .slice(1)
    .map((match) => {
      const cells = [...match[1].matchAll(/<td\b[^>]*>([\s\S]*?)<\/td>/g)].map(
        (cell) => cell[1],
      );
      // Eligibility notes follow the occupation name in the same source cell.
      const occupation = text(
        cells[socColumn].split(
          /<br\b| – Jobs with a working location| - ONLY /,
        )[0],
      );
      const codeAndTitle = occupation.match(/^(\d{4}) (.+)$/);
      if (!codeAndTitle)
        throw new Error(`Invalid occupation in Table ${table}: ${occupation}`);
      return {
        socCode: codeAndTitle[1],
        title: codeAndTitle[2],
        annualRate: text(cells[rateColumn]),
      };
    });
  return { header: headers[rateColumn], rows };
}

const goingRateRows = rateTables.flatMap((table) =>
  parseTable(table).rows.map((row) => {
    // Annual GBP appears first; the parenthesised hourly rate is not extracted.
    const amount = row.annualRate.match(/^£([\d,]+)(?:\s|$)/);
    if (!amount)
      throw new Error(
        `Missing annual going rate in Table ${table}: ${row.socCode}`,
      );
    return {
      socCode: row.socCode,
      title: row.title,
      goingRate: Number(amount[1].replaceAll(',', '')),
      table,
    };
  }),
);
const nationalPayScaleRows = parseTable('3').rows.map(({ socCode, title }) => ({
  socCode,
  title,
}));
const nationalPayScaleBelowRqf6Rows = parseTable('3a').rows.map(
  ({ socCode, title }) => ({ socCode, title }),
);

function quote(value) {
  return `'${value.replaceAll('\\', '\\\\').replaceAll("'", "\\'")}'`;
}

function renderRows(rows) {
  return rows
    .map((row) =>
      [
        '    {',
        ...Object.entries(row).map(([key, value]) => {
          const literal = typeof value === 'string' ? quote(value) : value;
          const line = `      ${key}: ${literal},`;
          return line.length > 80 ? `      ${key}:\n        ${literal},` : line;
        }),
        '    },',
      ].join('\n'),
    )
    .join('\n');
}

const headerNotes = rateTables
  .map((table) => `// Table ${table}: ${parseTable(table).header}.`)
  .join('\n');
const output = `import type { SourceRef } from '../types';

// Generated by scripts/extract-skilled-occupations.mjs; do not edit manually.
// SRC-017: policy-sources/${snapshot}.
${headerNotes}
// These columns give the full annual GBP rate for a 37.5-hour working week
// (Table 1 / 2 notes, inherited by the additional tables). Extract the first
// amount, not the parenthesised hourly rate or the 70% / 80% / 90% columns.
// Titles exclude subsequent eligibility notes; consult the source for restrictions.
// Table 3's "Going rate (annual)" contains national pay scales or Table 4 / 5
// references; retain codes and titles only, including separate regional rows.
// Table 3a retains codes and titles for the additional national pay scale jobs.
// Equivalent SOC 2010 columns and Tables 4 / 5 / 6 are not extracted.

export interface GoingRate {
  /** Four-digit SOC 2020 occupation code. */
  socCode: string;
  title: string;
  /** Annual going rate in GBP at the table's stated working-hours basis. */
  goingRate: number;
  table: '1' | '1a' | '2' | '2aa' | '2a' | '2b';
}

export const goingRates: { source: SourceRef; rows: GoingRate[] } = {
  source: {
    srcId: 'SRC-017',
    locator: 'Tables 1, 1a, 2, 2aa, 2a, 2b; SOC 2020 rows; Going rate columns',
  },
  rows: [
${renderRows(goingRateRows)}
  ],
};

/** Table 3 occupations whose going rates follow national pay scales. */
export const nationalPayScaleOccupations: {
  source: SourceRef;
  rows: { socCode: string; title: string }[];
} = {
  source: {
    srcId: 'SRC-017',
    locator: 'Table 3; SOC 2020 occupation code column',
  },
  rows: [
${renderRows(nationalPayScaleRows)}
  ],
};

/** Table 3a national pay scale occupations skilled to RQF levels 3–5. */
export const nationalPayScaleBelowRqf6Occupations: {
  sources: SourceRef[];
  occupations: { socCode: string; title: string }[];
} = {
  sources: [{ srcId: 'SRC-017', locator: 'Table 3a' }],
  occupations: [
${renderRows(nationalPayScaleBelowRqf6Rows)}
  ],
};
`;

writeFileSync(
  new URL('../src/data/skilled-occupations.ts', import.meta.url),
  output,
);
